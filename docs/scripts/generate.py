"""Write the generated pages of the documentation (SHIELD SH-22).

- ``docs/docs/policy/reference.mdx`` from ``schema/policy.schema.json``: every
  field, the classes, the scopes, the soft and hard limits;
- ``docs/docs/harnesses/register.mdx`` from agentspecs' ``register.yaml``
  through the package's register: each harness, its adapter and pin, its
  licence, its terms, its credential, and what each plane rolled (``docs/rolled.json``,
  refused when it is not what the register pins, SHIELD SH-42);
- ``docs/docs/api-reference/python.mdx`` from the package's docstrings: each
  module's first paragraph and its public names with their first line.

Run from the repository's root: ``python docs/scripts/generate.py``; with
``--check`` it exits 1 when a checked-in page differs from what it would
write now. The register needs ``datalayer-agent-shield[register]``.
"""

from __future__ import annotations

import ast
import importlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
DOCS = ROOT / "docs" / "docs"
SCHEMA = ROOT / "schema" / "policy.schema.json"
PACKAGE = ROOT / "agent_shield"

HEAD = "{/* GENERATED by docs/scripts/generate.py — do not edit; `python docs/scripts/generate.py` rewrites it. */}"


def _escape(text: str) -> str:
    return text.replace("{", "&#123;").replace("}", "&#125;").replace("<", "&lt;").replace("|", "\\|")


def _type_of(field: dict, defs: dict) -> str:
    if "$ref" in field:
        return field["$ref"].rsplit("/", 1)[-1]
    if "enum" in field:
        return " \\| ".join(f"`{v}`" for v in field["enum"])
    if "anyOf" in field:
        return " or ".join(_type_of(item, defs) for item in field["anyOf"])
    kind = field.get("type", "")
    if kind == "array":
        return f"list of {_type_of(field.get('items', {}), defs)}"
    return kind or "any"


def policy_reference() -> str:
    schema = json.loads(SCHEMA.read_text(encoding="utf8"))
    defs = schema.get("$defs", {})
    out = [
        "---",
        "sidebar_position: 2",
        "title: Policy reference",
        "---",
        HEAD,
        "",
        "# Policy reference",
        "",
        "The policy document, field by field, from `schema/policy.schema.json` — the one schema the Python package "
        "publishes (`agent-shield policy schema` prints it), the TypeScript types are generated from, and IAM validates "
        "an organization's document against.",
        "",
        f"**Built:** every field below is read by `agent_shield.policy` and decided on ({schema.get('title', 'the policy')}). "
        "**Not built:** nothing of this page is pending; a field that is not here is not a field.",
        "",
    ]

    def table(name: str, node: dict) -> None:
        out.append(f"## {name}")
        out.append("")
        if node.get("description"):
            out.append(_escape(node["description"].strip()))
            out.append("")
        required = set(node.get("required", []))
        out.append("| Field | Type | Required | What it says |")
        out.append("|---|---|---|---|")
        for key, field in node.get("properties", {}).items():
            out.append(
                f"| `{key}` | {_type_of(field, defs)} | {'yes' if key in required else 'no'} | "
                f"{_escape((field.get('description') or '').strip())} |"
            )
        out.append("")

    table("The document", schema)
    for name, node in defs.items():
        table(name, node)
    out.append("## The classes and the kinds")
    out.append("")
    rule = defs.get("Rule", {}).get("properties", {})
    classes = rule.get("classes", {}).get("items", {}).get("enum", [])
    kinds = rule.get("kinds", {}).get("items", {}).get("enum", [])
    out.append(f"Every action is classed as one of {', '.join(f'`{c}`' for c in classes)} (F-10); ACP's tool kinds are "
               f"{', '.join(f'`{k}`' for k in kinds)}, and `other` fails closed to `write`.")
    out.append("")
    out.append("## Soft and hard limits")
    out.append("")
    out.append("A `Threshold` has a `soft` count, where the next call asks the person once, and a `hard` count, where "
               "each further call is refused and the sentence says what would let the session go on. The limits are "
               "stateful per session; the strictest scope's decides first.")
    out.append("")
    return "\n".join(out)


def register_table() -> str:
    from agent_shield.register import catalogue  # the register extra

    out = [
        "---",
        "sidebar_position: 3",
        "title: The register",
        "---",
        HEAD,
        "",
        "# The register",
        "",
        "Every harness of the catalogue (agentspecs `harnesses/`), with its adapter and the version pinned, its "
        "licence, its terms, the credential it takes and whether serving it to third parties is permitted — the "
        "register `agent-shield harnesses` prints and `agent-shield setup` installs from.",
        "",
        "**Built:** the catalogue and the register come from agentspecs; `agent-shield setup --harness <id>` installs "
        "the pinned adapter of any npm-packaged one. **Not built:** the long tail of ACP agents beyond this table "
        "is a register tier listed on request (SHIELD SH-57).",
        "",
        "| Harness | Adapter | Pinned | Credential | Third parties | Licence | Needs |",
        "|---|---|---|---|---|---|---|",
    ]
    for harness_id, harness in sorted(catalogue().items()):
        entry = harness.entry
        served = getattr(entry.served_to_third_parties, "value", entry.served_to_third_parties)
        out.append(
            f"| **{harness.name}** (`{harness_id}`) | `{harness.adapter}` | {harness.version} | "
            f"{_escape(entry.credential)} | `{served}` | {_escape(entry.licence)} | {_escape(entry.binaries or '')} |"
        )
    out.append("")
    out += rolled_section({harness_id: harness.version for harness_id, harness in catalogue().items()})
    out.append("## Terms, as read")
    out.append("")
    for harness_id, harness in sorted(catalogue().items()):
        entry = harness.entry
        out.append(f"### {harness.name}")
        out.append("")
        out.append(_escape((entry.note or "").strip()))
        if entry.tier_restrictions:
            out.append("")
            out.append(f"Tiers: {_escape(entry.tier_restrictions)}")
        out.append("")
        out.append(f"Read at {entry.terms_source} and {entry.licence_source}.")
        out.append("")
    return "\n".join(out)


def rolled_section(pinned: dict[str, str]) -> list[str]:
    """What each plane runs (SH-42), from ``docs/rolled.json``; a version the register does not pin is refused."""
    data = json.loads((ROOT / "docs" / "rolled.json").read_text(encoding="utf8"))
    out = [
        "## Rolled where",
        "",
        "The harnesses are rolled apart from the runtime image, in the `datalayer-harnesses` image, and each roll is "
        "read inside the image it ships (`check_register.py --image … --markdown` in Datalayer's services): what each "
        "plane runs, against what the register pins.",
        "",
        "| Plane | Image | Harness | Rolled | Pinned | Since | Operator |",
        "|---|---|---|---|---|---|---|",
    ]
    notes = []
    for roll in data["rolls"]:
        for harness_id, version in sorted(roll["harnesses"].items()):
            if pinned.get(harness_id) != version:
                raise SystemExit(
                    f"docs/rolled.json says {roll['plane']} rolled {harness_id} {version}; the register pins "
                    f"{pinned.get(harness_id) or 'nothing'}: roll the register's, or pin what is rolled"
                )
            out.append(
                f"| {roll['plane']} | `{roll['image']}` | `{harness_id}` | {version} | {pinned[harness_id]} | "
                f"{roll['since']} | {roll['operator']} |"
            )
        if roll.get("sidecar"):
            notes.append(f"On {roll['plane']}, the sidecar: {_escape(roll['sidecar'])}.")
    out.append("")
    out += [*notes, ""] if notes else []
    return out


def python_api() -> str:
    out = [
        "---",
        "sidebar_position: 1",
        "title: Python",
        "---",
        HEAD,
        "",
        "# Python: `agent_shield`",
        "",
        "Every module of the package and its public names, from their docstrings' first lines.",
        "",
        "**Built:** everything listed here exists in the package at this version. **Not built:** nothing is listed "
        "that does not exist; the plan's pending boxes are on the front page.",
        "",
    ]
    for path in sorted(PACKAGE.rglob("*.py")):
        if path.name.startswith("_") and path.name != "__init__.py":
            continue
        relative = path.relative_to(ROOT).with_suffix("")
        parts = list(relative.parts)
        if parts[-1] == "__init__":
            parts = parts[:-1]
        module = ".".join(parts)
        try:
            tree = ast.parse(path.read_text(encoding="utf8"))
        except SyntaxError as error:
            print(f"skipped {relative}: it does not parse ({error.msg} at line {error.lineno})", file=sys.stderr)
            continue
        doc = ast.get_docstring(tree) or ""
        first = doc.strip().split("\n\n", 1)[0].replace("\n", " ") if doc else ""
        names: list[tuple[str, str]] = []
        for node in tree.body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and not node.name.startswith("_"):
                line = (ast.get_docstring(node) or "").strip().split("\n", 1)[0]
                names.append((node.name, line))
        if not first and not names:
            continue
        out.append(f"## `{module}`")
        out.append("")
        if first:
            out.append(_escape(first))
            out.append("")
        for name, line in names:
            out.append(f"- `{name}`" + (f" — {_escape(line)}" if line else ""))
        out.append("")
    return "\n".join(out)


PAGES = {
    DOCS / "policy" / "reference.mdx": policy_reference,
    DOCS / "harnesses" / "register.mdx": register_table,
    DOCS / "api-reference" / "python.mdx": python_api,
}


def main() -> int:
    check = "--check" in sys.argv
    problems = 0
    for path, make in PAGES.items():
        text = make()
        if check:
            current = path.read_text(encoding="utf8") if path.is_file() else None
            if current != text:
                print(f"{path.relative_to(ROOT)} differs from what the generator gives: run python docs/scripts/generate.py")
                problems += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf8")
            print(f"wrote {path.relative_to(ROOT)}")
    if check and not problems:
        print(f"{len(PAGES)} generated pages are what the generator gives")
    return 1 if problems else 0


if __name__ == "__main__":
    importlib.invalidate_caches()
    sys.exit(main())
